    public Project loadProject(File projectDir, Context context) throws LoadingProjectException, IOException {
        Project project;
        cleanUpTmpCodeFile(projectDir);
        File file = new File(projectDir, Constants.CODE_XML_FILE_NAME);
        if (!file.exists()) {
            throw new FileNotFoundException(file.getAbsolutePath() + " does not exist.");
        }
        file.setLastModified(System.currentTimeMillis());
        try {
            try {
                this.loadSaveLock.lock();
                ProjectData projectMetaData = new ProjectMetaDataParser(file).getProjectMetaData();
                if (!projectMetaData.hasScenes()) {
                    new File(projectDir, Constants.IMAGE_DIRECTORY_NAME).mkdir();
                    new File(projectDir, Constants.SOUND_DIRECTORY_NAME).mkdir();
                    prepareXstream(LegacyProjectWithoutScenes.class, Scene.class);
                    LegacyProjectWithoutScenes legacyProjectWithoutScenes = (LegacyProjectWithoutScenes) this.xstream.getProjectFromXML(file);
                    prepareXstream(Project.class, Scene.class);
                    project = legacyProjectWithoutScenes.toProject(context);
                } else if (projectMetaData.getLanguageVersion() < 0.9991d) {
                    prepareXstream(ProjectUntilLanguageVersion0999.class, SceneUntilLanguageVersion0999.class);
                    ProjectUntilLanguageVersion0999 projectUntilLanguageVersion0999 = (ProjectUntilLanguageVersion0999) this.xstream.getProjectFromXML(file);
                    prepareXstream(Project.class, Scene.class);
                    project = projectUntilLanguageVersion0999.toProject();
                } else {
                    prepareXstream(Project.class, Scene.class);
                    project = (Project) this.xstream.getProjectFromXML(file);
                    Iterator<Scene> it = project.getSceneList().iterator();
                    while (it.hasNext()) {
                        it.next().setProject(project);
                    }
                }
                project.checkForInvisibleSprites();
                project.setDirectory(projectDir);
                setFileReferences(project);
                this.loadSaveLock.unlock();
                return project;
            } catch (Exception e) {
                throw new LoadingProjectException("Cannot load project from " + projectDir.getAbsolutePath() + "\nException: " + e.getLocalizedMessage());
            }
        } catch (Throwable th) {
            this.loadSaveLock.unlock();
            throw th;
        }
    }

    public static boolean renameProject(File xmlFile, String destinationName) throws Throwable {
        if (!xmlFile.exists()) {
            throw new FileNotFoundException(xmlFile + " does not exist.");
        }
        String str = Files.asCharSource(xmlFile, Charsets.UTF_8).read();
        String strFindBetween = new StringFinder().findBetween(str, PROGRAM_NAME_START_TAG, PROGRAM_NAME_END_TAG);
        if (strFindBetween == null) {
            return false;
        }
        String xMLEncodedString = getXMLEncodedString(destinationName);
        if (strFindBetween.equals(xMLEncodedString)) {
            return true;
        }
        String strReplace = str.replace(PROGRAM_NAME_START_TAG + strFindBetween + PROGRAM_NAME_END_TAG, PROGRAM_NAME_START_TAG + xMLEncodedString + PROGRAM_NAME_END_TAG);
        if (str.equals(strReplace)) {
            Log.e(TAG, "Cannot find projectNameTag in code.xml");
            return false;
        }
        StorageOperations.writeToFile(xmlFile, strReplace);
        return true;
    }

    private static String getXMLEncodedString(String sourceName) {
        return new XStream().toXML(sourceName).replace("<string>", "").replace("</string>", "");
    }

    private static void setFileReferences(Project project) {
        for (Scene scene : project.getSceneList()) {
            File file = new File(scene.getDirectory(), Constants.IMAGE_DIRECTORY_NAME);
            File file2 = new File(scene.getDirectory(), Constants.SOUND_DIRECTORY_NAME);
            for (Sprite sprite : scene.getSpriteList()) {
                Iterator<LookData> it = sprite.getLookList().iterator();
                while (it.hasNext()) {
                    LookData next = it.next();
                    File file3 = new File(file, next.getXstreamFileName());
                    if (file3.exists()) {
                        next.setFile(file3);
                    } else {
                        it.remove();
                    }
                }
                Iterator<SoundInfo> it2 = sprite.getSoundList().iterator();
                while (it2.hasNext()) {
                    SoundInfo next2 = it2.next();
                    File file4 = new File(file2, next2.getXstreamFileName());
                    if (file4.exists()) {
                        next2.setFile(file4);
                    } else {
                        it2.remove();
                    }
                }
            }
        }
    }

    private boolean unnecessaryChanges(String currentXml, String previousXml) {
        Pattern patternCompile = Pattern.compile("<formula category=\".*Y.*\">", 2);
        Pattern patternCompile2 = Pattern.compile("<formula category=\".*X.*\">", 2);
        Matcher matcher = patternCompile.matcher(currentXml);
        Matcher matcher2 = patternCompile2.matcher(previousXml);
        matcher.find();
        matcher2.find();
        return matcher2.matches() && matcher.matches() && currentXml.indexOf(matcher2.group(0)) == previousXml.indexOf(matcher.group(0));
    }

    public boolean saveProject(Project project) {
        if (project == null) {
            return false;
        }
        try {
            cleanUpTmpCodeFile(project.getDirectory());
            this.loadSaveLock.lock();
            if (BuildConfig.FLAVOR.equals("pocketCodeBeta")) {
                project.getXmlHeader().setApplicationBuildType("debug");
            } else {
                project.getXmlHeader().setApplicationBuildType(BuildConfig.BUILD_TYPE);
            }
            try {
                try {
                    String strConcat = XML_HEADER.concat(this.xstream.toXML(project));
                    File file = new File(project.getDirectory(), Constants.TMP_CODE_XML_FILE_NAME);
                    File file2 = new File(project.getDirectory(), Constants.CODE_XML_FILE_NAME);
                    if (file2.exists()) {
                        try {
                            String str = Files.asCharSource(file2, Charsets.UTF_8).read();
                            if (str.equals(strConcat)) {
                                Log.d(TAG, "Project version is the same. Do not update " + file2.getName());
                                return false;
                            }
                            Pattern patternCompile = Pattern.compile("<catrobatLanguageVersion>.*</catrobatLanguageVersion>", 2);
                            Matcher matcher = patternCompile.matcher(strConcat);
                            Matcher matcher2 = patternCompile.matcher(str);
                            matcher.find();
                            matcher2.find();
                            if (Objects.equals(matcher.group(0), matcher2.group(0)) && !unnecessaryChanges(strConcat, str)) {
                                ProjectManager.getInstance().changedProject(project.getName());
                            }
                        } catch (Exception e) {
                            Log.e(TAG, "Opening project at " + file2.getAbsolutePath() + " failed.", e);
                        }
                    }
                    StorageOperations.createDir(FlavoredConstants.DEFAULT_ROOT_DIRECTORY);
                    StorageOperations.createDir(project.getDirectory());
                    Iterator<Scene> it = project.getSceneList().iterator();
                    while (it.hasNext()) {
                        StorageOperations.createSceneDirectory(it.next().getDirectory());
                    }
                    StorageOperations.writeToFile(file, strConcat);
                    if (file2.exists() && !file2.delete()) {
                        Log.e(TAG, "Cannot delete " + file2.getName());
                    }
                    if (!file.renameTo(file2)) {
                        Log.e(TAG, "Cannot rename code.xml for " + project.getName());
                    }
                    return true;
                } catch (Exception e2) {
                    Log.e(TAG, "Saving project " + project.getName() + " failed.", e2);
                }
            } finally {
                this.loadSaveLock.unlock();
            }
        } catch (LoadingProjectException unused) {
            return false;
        }
    }

    private void cleanUpTmpCodeFile(File projectDir) throws LoadingProjectException {
        this.loadSaveLock.lock();
        File file = new File(projectDir, Constants.TMP_CODE_XML_FILE_NAME);
        File file2 = new File(projectDir, Constants.CODE_XML_FILE_NAME);
        try {
            if (file.exists()) {
                if (file2.exists()) {
                    file.delete();
                } else if (!file.renameTo(file2)) {
                    throw new LoadingProjectException("code.xml did not exist. But wait, renaming " + file.getAbsolutePath() + " failed too.");
                }
            }
            this.loadSaveLock.unlock();
        } catch (Throwable th) {
            this.loadSaveLock.unlock();
            throw th;
        }
    }

    public String getXmlAsStringFromProject(Project project) {
        this.loadSaveLock.lock();
        try {
            prepareXstream(project.getClass(), project.getSceneList().get(0).getClass());
            String xml = this.xstream.toXML(project);
            prepareXstream(Project.class, Scene.class);
            return xml;
        } finally {
            this.loadSaveLock.unlock();
        }
    }

    public static String extractDefaultSceneNameFromXml(File projectDir) {
        File file = new File(projectDir, Constants.CODE_XML_FILE_NAME);
        try {
            return new StringFinder().findBetween(Files.asCharSource(file, Charsets.UTF_8).read(), "<scenes>\\s*<scene>\\s*<name>", "</name>");
        } catch (IOException e) {
            Log.e(TAG, Log.getStackTraceString(e));
            return null;
        }
    }

    public BackwardCompatibleCatrobatLanguageXStream getXstream() {
        return this.xstream;
    }
